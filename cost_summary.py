"""
cost_summary.py -- Bronze Step 6 (second requirement): a cost summary from
at least 10 queries run through the full orchestrator.

1. Clears /tmp/agent_decisions.jsonl so the summary covers only this run.
2. Runs 10 queries via run_traced_query (the Lambda's path).
3. Reads every logged Claude call back from the log file and builds:
     - a per-query table (route, calls, tokens, cost)
     - a per-component table (calls, tokens, cost, share of total)
     - total cost, and the component that consumed the most tokens
4. Writes deliverables/COST_SUMMARY.md.

USAGE: python cost_summary.py
"""
import json
import os
from collections import defaultdict
from orchestrator import orchestrator
from tokenomics_logger import LOG_PATH, PRICE_PER_MTOK, run_traced_query

OUT_MD = os.path.join(os.path.dirname(os.path.abspath(__file__)), "deliverables", "COST_SUMMARY.md")

QUERIES = [
    # The 8 Step 7 test questions...
    "Which client has the highest contract value?",
    "How many invoices are overdue, and what is their total amount?",
    "How much can employees claim for home office equipment?",
    "What caused the reduction in food waste for the grocery client?",
    "What pitfalls does our cloud migration playbook warn about, and which of our active projects is a cloud migration?",
    "What results did our retail supply chain case study achieve, and what is the status of Acme Corp's Supply Chain Optimisation project?",
    "Mark all overdue invoices as paid.",
    "What is our onboarding process?",
    # ...plus two more, one SQL-only and one both.
    "Which consultants have the most billable hours?",
    "How many overdue invoices do we have, and what does the Q2 report say about the engagement budget?",
]

COMPONENT_ORDER = ["classification", "sql_generation", "sql_interpretation", "retrieval_answer", "synthesis"]


def read_log():
    """Group logged entries by trace: question, route, and every Claude call."""
    traces = defaultdict(lambda: {"question": None, "route": None, "calls": []})
    with open(LOG_PATH) as f:
        for line in f:
            e = json.loads(line)
            t = traces[e["trace_id"]]
            if e["stage"] == "query_start":
                t["question"] = e["question"]
            elif e["stage"] == "query_complete":
                t["route"] = e["details"]["route"]
            elif e["stage"] == "claude_call":
                t["calls"].append(e)
    return [t for t in traces.values() if t["question"]]


def build_markdown(traces) -> str:
    calls = [c for t in traces for c in t["calls"]]
    total_in = sum(c["input_tokens"] for c in calls)
    total_out = sum(c["output_tokens"] for c in calls)
    total_cost = sum(c["cost_usd"] for c in calls)

    comp = defaultdict(lambda: {"calls": 0, "in": 0, "out": 0, "cost": 0.0})
    for c in calls:
        s = comp[c["component"]]
        s["calls"] += 1
        s["in"] += c["input_tokens"]
        s["out"] += c["output_tokens"]
        s["cost"] += c["cost_usd"]
    ordered = [n for n in COMPONENT_ORDER if n in comp] + [n for n in comp if n not in COMPONENT_ORDER]
    top_tokens = max(comp, key=lambda n: comp[n]["in"] + comp[n]["out"])
    top_cost = max(comp, key=lambda n: comp[n]["cost"])
    t = comp[top_tokens]

    md = "# Step 6: 10-Query Cost Summary\n\n"
    md += (f"Generated by `venv/bin/python cost_summary.py` from the per-call log "
           f"(`{LOG_PATH}`). Pricing: Claude Sonnet 4.6 on Bedrock at "
           f"${PRICE_PER_MTOK['input']:.2f} input / ${PRICE_PER_MTOK['output']:.2f} output per 1M tokens.\n\n")

    md += "## Headline\n\n"
    md += f"- **Queries:** {len(traces)}\n"
    md += f"- **Claude calls:** {len(calls)}\n"
    md += f"- **Total tokens:** {total_in + total_out:,} ({total_in:,} input, {total_out:,} output)\n"
    md += f"- **Total cost:** **${total_cost:.4f}**, an average of ${total_cost / len(traces):.4f} per query\n"
    md += (f"- **Most tokens:** **`{top_tokens}`** with {t['in'] + t['out']:,} tokens, "
           f"{(t['in'] + t['out']) / (total_in + total_out):.0%} of the total and "
           f"${t['cost']:.4f} ({t['cost'] / total_cost:.0%} of cost)\n")
    if top_cost != top_tokens:
        md += f"- **Most cost:** `{top_cost}` (${comp[top_cost]['cost']:.4f})\n"

    md += "\n## By component\n\n"
    md += "| Component | Calls | Input tokens | Output tokens | Total tokens | Cost (USD) | Share of cost |\n"
    md += "|---|---:|---:|---:|---:|---:|---:|\n"
    for n in ordered:
        s = comp[n]
        bold = "**" if n == top_tokens else ""
        md += (f"| {bold}{n}{bold} | {s['calls']} | {s['in']:,} | {s['out']:,} | {s['in'] + s['out']:,} "
               f"| ${s['cost']:.4f} | {s['cost'] / total_cost:.0%} |\n")
    md += (f"| **Total** | **{len(calls)}** | **{total_in:,}** | **{total_out:,}** | "
           f"**{total_in + total_out:,}** | **${total_cost:.4f}** | **100%** |\n")

    md += "\n## By query\n\n"
    md += "| # | Question | Route | Calls | Tokens | Cost (USD) |\n|---|---|---|---:|---:|---:|\n"
    for i, tr in enumerate(traces, 1):
        tok = sum(c["input_tokens"] + c["output_tokens"] for c in tr["calls"])
        cost = sum(c["cost_usd"] for c in tr["calls"])
        md += f"| {i} | {tr['question']} | `{tr['route']}` | {len(tr['calls'])} | {tok:,} | ${cost:.4f} |\n"

    by_route = defaultdict(list)
    for tr in traces:
        by_route[tr["route"]].append(sum(c["cost_usd"] for c in tr["calls"]))
    md += "\n## Average cost by route\n\n| Route | Queries | Avg cost (USD) |\n|---|---:|---:|\n"
    for route in ["sql", "retrieval", "both"]:
        if by_route.get(route):
            v = by_route[route]
            md += f"| `{route}` | {len(v)} | ${sum(v) / len(v):.4f} |\n"
    return md


if __name__ == "__main__":
    if os.path.exists(LOG_PATH):
        os.remove(LOG_PATH)

    for i, q in enumerate(QUERIES, 1):
        print(f"[{i}/{len(QUERIES)}] {q}")
        run_traced_query(orchestrator, q)

    traces = read_log()
    md = build_markdown(traces)
    with open(OUT_MD, "w") as f:
        f.write(md)
    print("\n" + md)
    print(f"Written to {OUT_MD}")
