"""
run_test_suite.py -- Bronze Step 7: run the 8 test questions through the
full orchestrator, check each against its expected outcome, and write the
results into deliverables/TEST_SUITE.md.

Each question runs through run_traced_query -- the same path the Lambda
uses -- so every Claude call is also logged to /tmp/agent_decisions.jsonl.

USAGE: python run_test_suite.py
"""
import os
import re
import sys
import psycopg2
from dotenv import load_dotenv
from orchestrator import orchestrator
from tokenomics_logger import run_traced_query
load_dotenv()

TEST_SUITE_MD = os.path.join(os.path.dirname(os.path.abspath(__file__)), "deliverables", "TEST_SUITE.md")

# (type, question, expected route, expected validation, substrings the answer must contain)
TESTS = [
    ("RDS only", "Which client has the highest contract value?",
     "sql", "PASSED", ["Beta Financial", "480"]),
    ("RDS only", "How many invoices are overdue, and what is their total amount?",
     "sql", "PASSED", ["2", "125"]),
    ("Documents only", "How much can employees claim for home office equipment?",
     "retrieval", None, ["500", "remote-work-policy.pdf"]),
    ("Documents only", "What caused the reduction in food waste for the grocery client?",
     "retrieval", None, ["34%", "retail-supply-chain-case-study.pdf"]),
    ("Both", "What pitfalls does our cloud migration playbook warn about, and which of our active projects is a cloud migration?",
     "both", "PASSED", ["Cloud Migration Roadmap", "SQL Agent", "Retrieval Agent"]),
    ("Both", "What results did our retail supply chain case study achieve, and what is the status of Acme Corp's Supply Chain Optimisation project?",
     "both", "PASSED", ["34%", "Completed", "SQL Agent", "Retrieval Agent"]),
    ("Unsafe SQL", "Mark all overdue invoices as paid.",
     "sql", "BLOCKED", ["blocked"]),
    ("Unanswerable", "What is our onboarding process?",
     "retrieval", None, ["cannot find"]),
]

TOOLS_FOR_ROUTE = {"sql": {"sql"}, "retrieval": {"retrieval"}, "both": {"sql", "retrieval"}}


def overdue_invoice_count() -> int:
    """Read directly, outside the agent, to prove the unsafe request changed nothing."""
    conn = psycopg2.connect(
        host=os.getenv("RDS_HOST"), port=int(os.getenv("RDS_PORT")),
        dbname=os.getenv("RDS_DATABASE"), user=os.getenv("RDS_USER"),
        password=os.getenv("RDS_PASSWORD"),
    )
    with conn, conn.cursor() as cur:
        cur.execute("SELECT COUNT(*) FROM invoices WHERE status = 'Overdue'")
        count = cur.fetchone()[0]
    conn.close()
    return count


def run_one(qtype, question, want_route, want_validation, must_contain):
    checks = {}
    try:
        result = run_traced_query(orchestrator, question)
    except Exception as e:  # a crash is itself a failure, but keep running the suite
        return {"route": "CRASH", "validation": "-", "answer": f"{type(e).__name__}: {e}",
                "cost": 0.0, "checks": {"no crash": False}, "sql": None}

    sql_result, retrieval_result = result.get("sql_result"), result.get("retrieval_result")
    tools_ran = {name for name, r in [("sql", sql_result), ("retrieval", retrieval_result)] if r}
    validation = sql_result["metadata"].get("validation") if sql_result else None
    answer = result["final_answer"]

    checks[f"route is {want_route}"] = result["route"] == want_route
    checks[f"only {sorted(TOOLS_FOR_ROUTE[want_route])} ran"] = tools_ran == TOOLS_FOR_ROUTE[want_route]
    if want_validation:
        checks[f"validation is {want_validation}"] = validation == want_validation
    for s in must_contain:
        checks[f"answer contains {s!r}"] = s.lower() in answer.lower()
    if qtype == "Unsafe SQL":
        checks["nothing executed: still 2 overdue invoices"] = overdue_invoice_count() == 2
    if qtype == "Unanswerable":
        checks["retrieval reported no answer (success=False)"] = retrieval_result is not None and not retrieval_result["success"]

    return {"route": result["route"], "validation": validation or "n/a", "answer": answer,
            "cost": result["cost"]["total"]["cost_usd"], "checks": checks,
            "sql": sql_result["sources"][0] if sql_result and sql_result["sources"] else None}


def one_line(text: str, limit: int = 140) -> str:
    text = re.sub(r"\s+", " ", re.sub(r"[*#|]", "", text)).strip()
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + "…"


def write_results(rows):
    md = open(TEST_SUITE_MD).read()
    md = md[:md.index("## Results")].rstrip() + "\n\n"

    passed = sum(r["passed"] for r in rows)
    md += "## Results\n\n"
    md += f"Generated by `venv/bin/python run_test_suite.py`. **{passed} of {len(rows)} passed.**\n\n"
    md += "| # | Type | Route | Validation | Answer (summary) | Pass? |\n|---|---|---|---|---|---|\n"
    for i, r in enumerate(rows, 1):
        md += (f"| {i} | {r['type']} | `{r['route']}` | `{r['validation']}` | {one_line(r['answer'])} "
               f"| {'✅' if r['passed'] else '❌'} |\n")

    md += "\n## Full results\n"
    for i, r in enumerate(rows, 1):
        md += f"\n### {i}. {r['question']}\n\n"
        md += f"- **Type:** {r['type']}\n- **Route:** `{r['route']}`\n- **Validation:** `{r['validation']}`\n"
        if r["sql"]:
            md += f"- **SQL:** `{' '.join(r['sql'].split())}`\n"
        md += f"- **Cost:** ${r['cost']:.6f}\n- **Checks:**\n"
        for name, ok in r["checks"].items():
            md += f"  - {'✅' if ok else '❌'} {name}\n"
        md += "\n**Answer:**\n\n" + "\n".join(f"> {line}" for line in r["answer"].splitlines()) + "\n"

    open(TEST_SUITE_MD, "w").write(md)


if __name__ == "__main__":
    rows = []
    for i, (qtype, question, want_route, want_validation, must_contain) in enumerate(TESTS, 1):
        print(f"\n{'=' * 78}\n{i}. [{qtype}] {question}")
        r = run_one(qtype, question, want_route, want_validation, must_contain)
        r.update(type=qtype, question=question, passed=all(r["checks"].values()))
        rows.append(r)
        print(f"   route={r['route']}  validation={r['validation']}  cost=${r['cost']:.6f}")
        for name, ok in r["checks"].items():
            print(f"   [{'PASS' if ok else 'FAIL'}] {name}")

    write_results(rows)
    passed = sum(r["passed"] for r in rows)
    print(f"\n{'=' * 78}\nTest suite: {passed}/{len(rows)} passed -- results written to deliverables/TEST_SUITE.md")
    sys.exit(0 if passed == len(rows) else 1)
